// Native dialogs (React Native's Alert, which is AppCompat's AlertDialog) in
// the app's dark System 02 look, always.
// - Expo's AppTheme is Theme.AppCompat.DayNight, so a dialog followed the
//   phone's day/night setting and came out white on some phones and screens
//   (device pass, 2026-11). This gives AppTheme a fixed dark dialog theme:
//   panel surface with 4dp corners, cream title, body text for the message.
// - Buttons: Android places the last button of Alert.alert on the right
//   (positive) and React Native ignores `style: "destructive"` there, so the
//   action (Delete, Forget, Discard: always last in this app) is cream and
//   medium weight, Cancel and the other buttons are the muted engrave grey.
//   Red per button isn't possible with the native dialog.
// Colours come from src/tokens.ts (values copied: plugins run in Node on the
// JS config, without TypeScript); plugins.test.mjs checks they match.
const { withAndroidColors, withAndroidStyles, withDangerousMod } = require("expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

const COLORS = {
  hivo_dialog_surface: "#161614", // C.panel
  hivo_dialog_rule: "#3d3c37", // C.ruleStrong
  hivo_dialog_title: "#f2efe8", // C.cream
  hivo_dialog_text: "#c9c5bb", // C.body
  hivo_dialog_muted: "#8d897f", // C.engrave
};

const DIALOG = "Theme.Hivo.Dialog";
// The title has its own style with the cream colour set explicitly: React
// Native's title view takes ?android:windowTitleStyle from the activity theme
// (DayNight's light text appearance), so it came out near-black on the dark
// surface ("Recording notification" was unreadable, 2026-11-10).
const TITLE = "Widget.Hivo.Dialog.Title";
const TITLE_TEXT = "TextAppearance.Hivo.Dialog.Title";
const POSITIVE = "Widget.Hivo.Dialog.Positive";
const OTHER = "Widget.Hivo.Dialog.Other";
const DRAWABLE = "hivo_dialog_background";

const DRAWABLE_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withDarkDialogs.js -->
<inset xmlns:android="http://schemas.android.com/apk/res/android"
    android:insetLeft="16dp" android:insetTop="16dp" android:insetRight="16dp" android:insetBottom="16dp">
  <shape android:shape="rectangle">
    <corners android:radius="4dp" />
    <solid android:color="@color/hivo_dialog_surface" />
    <stroke android:width="1dp" android:color="@color/hivo_dialog_rule" />
  </shape>
</inset>
`;

const item = (name, value) => ({ $: { name }, _: value });

function setItem(style, name, value) {
  style.item = style.item ?? [];
  const found = style.item.find((i) => i.$?.name === name);
  if (found) found._ = value;
  else style.item.push(item(name, value));
}

function setStyle(resources, name, parent, items) {
  resources.style = resources.style ?? [];
  let style = resources.style.find((s) => s.$?.name === name);
  if (!style) {
    style = { $: { name, parent }, item: [] };
    resources.style.push(style);
  }
  style.$.parent = parent;
  for (const [k, v] of items) setItem(style, k, v);
  return style;
}

/** Adds the dialog styles and points AppTheme at them. Idempotent. */
function applyDialogStyles(styles) {
  const res = styles.resources;
  setStyle(res, POSITIVE, "Widget.AppCompat.Button.ButtonBar.AlertDialog", [
    ["android:textColor", "@color/hivo_dialog_title"],
    ["android:fontFamily", "sans-serif-medium"],
  ]);
  setStyle(res, OTHER, "Widget.AppCompat.Button.ButtonBar.AlertDialog", [["android:textColor", "@color/hivo_dialog_muted"]]);
  setStyle(res, TITLE_TEXT, "TextAppearance.AppCompat.Title", [["android:textColor", "@color/hivo_dialog_title"]]);
  setStyle(res, TITLE, "RtlOverlay.DialogWindowTitle.AppCompat", [
    ["android:textAppearance", `@style/${TITLE_TEXT}`],
    ["android:textColor", "@color/hivo_dialog_title"],
  ]);
  setStyle(res, DIALOG, "Theme.AppCompat.Dialog.Alert", [
    ["android:windowTitleStyle", `@style/${TITLE}`],
    ["android:windowBackground", `@drawable/${DRAWABLE}`],
    ["android:colorBackground", "@color/hivo_dialog_surface"],
    ["colorBackgroundFloating", "@color/hivo_dialog_surface"],
    ["android:textColorPrimary", "@color/hivo_dialog_title"],
    ["android:textColorSecondary", "@color/hivo_dialog_text"],
    ["android:textColorAlertDialogListItem", "@color/hivo_dialog_title"],
    ["colorAccent", "@color/hivo_dialog_title"],
    ["buttonBarPositiveButtonStyle", `@style/${POSITIVE}`],
    ["buttonBarNegativeButtonStyle", `@style/${OTHER}`],
    ["buttonBarNeutralButtonStyle", `@style/${OTHER}`],
  ]);
  const app = (res.style ?? []).find((s) => s.$?.name === "AppTheme");
  if (app) {
    setItem(app, "alertDialogTheme", `@style/${DIALOG}`);
    setItem(app, "android:alertDialogTheme", `@style/${DIALOG}`);
    // React Native draws Alert titles with its own layout
    // (alert_title_layout.xml: style="?android:attr/windowTitleStyle"),
    // inflated with the activity's context: the attribute is read from
    // AppTheme, not the dialog theme. AppTheme has no window title bar
    // (NoActionBar), so this only reaches those dialog titles.
    setItem(app, "android:windowTitleStyle", `@style/${TITLE}`);
  }
  return styles;
}

/** Adds (or updates) the dialog colours. Idempotent. */
function applyDialogColors(colors) {
  const res = colors.resources;
  res.color = res.color ?? [];
  for (const [name, value] of Object.entries(COLORS)) {
    const found = res.color.find((c) => c.$?.name === name);
    if (found) found._ = value;
    else res.color.push(item(name, value));
  }
  return colors;
}

const withDarkDialogs = (config) => {
  config = withAndroidColors(config, (c) => {
    c.modResults = applyDialogColors(c.modResults);
    return c;
  });
  config = withAndroidStyles(config, (c) => {
    c.modResults = applyDialogStyles(c.modResults);
    return c;
  });
  return withDangerousMod(config, [
    "android",
    (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, "app", "src", "main", "res", "drawable");
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${DRAWABLE}.xml`), DRAWABLE_XML);
      return c;
    },
  ]);
};

module.exports = withDarkDialogs;
module.exports.applyDialogStyles = applyDialogStyles;
module.exports.applyDialogColors = applyDialogColors;
module.exports.COLORS = COLORS;
module.exports.DRAWABLE_XML = DRAWABLE_XML;
